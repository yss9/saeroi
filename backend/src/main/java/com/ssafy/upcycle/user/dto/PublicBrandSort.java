package com.ssafy.upcycle.user.dto;

/**
 * 브랜드 목록 정렬 기준.
 *
 * <p>둘 다 마지막 키가 {@code brandId} 다. 앞 키의 값이 같은 브랜드들의 순서가 페이지마다
 * 달라지면 <b>같은 브랜드가 1페이지와 2페이지에 동시에 보이거나 어느 쪽에도 안 보인다.</b>
 * 상품 목록이 {@code id} 를 마지막에 두는 것과 같은 이유이며, 브랜드는 수가 적어 상품 수가
 * 같은 경우가 훨씬 흔하다.
 */
public enum PublicBrandSort {

    /**
     * 판매 중인 공개 상품이 많은 브랜드부터. 기준을 주지 않으면 이것이다.
     *
     * <p>BRANDS 첫 화면에서 볼 것이 많은 브랜드가 먼저 나오는 편이 탐색에 낫다. 상품이
     * 하나도 없는 브랜드는 애초에 목록에 실리지 않는다.
     */
    PRODUCT_COUNT,

    /**
     * 화면에 보이는 이름 오름차순.
     *
     * <p>정렬 순서는 DB 의 collation 이 정한다 — 한글 이름의 순서가 운영(MySQL)과 테스트(H2)
     * 에서 다를 수 있어, 순서를 고정하는 테스트는 영문 이름 표본으로만 단언한다.
     */
    NAME
}
