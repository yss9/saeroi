package com.ssafy.upcycle.evidence.dto;

/**
 * 증빙 목록을 <b>어느 범위까지 보여준 응답인가</b>. S15P21E104-286 §6-1.
 *
 * <p>이 값이 응답에 실려 나가는 것이 이 설계의 핵심이다. 필드를 조용히 빼고 내려주면
 * 프론트는 <b>"값이 없는 것"과 "가려진 것"을 구분할 수 없다</b> — 계근표가 아직 안 올라온
 * 소재와, 남의 소재라 파일명을 못 보는 상태가 같은 모양이 된다. 앞의 것은 "올려 주세요" 이고
 * 뒤의 것은 "권한이 없습니다" 인데, 화면이 둘을 같은 문구로 말하게 된다.
 *
 * <p>그래서 <b>가려졌다는 사실 자체를 값으로 만든다.</b> 새 민감 필드가 추가될 때도
 * 이 판정 하나만 보면 되고, 프론트는 필드별로 null 을 해석하지 않는다.
 */
public enum EvidenceListVisibility {

    /**
     * 전체. 업로더 · 소재 등록자 · 그 소재의 현재 보유자 ({@code EvidenceAccessPolicy} 와
     * <b>같은 관계 판정</b>이다 — 두 벌이 되면 {@code /content} 는 열리는데 목록은 막히는
     * 상태가 조용히 생긴다).
     */
    FULL,

    /**
     * 요약만. 증빙 종류별 개수까지다.
     *
     * <p>파일명({@code storageKey}) · {@code contentPath} · {@code fileHash} · 업로더를
     * <b>싣지 않는다.</b> {@code 계근표_OO상사.pdf} 같은 이름만으로도 거래 상대가 드러나고,
     * 계근표에는 중량·단가가 찍혀 있다.
     *
     * <p>목록을 통째로 403 으로 막지 않은 이유는 소재 상세가 <b>추적성 화면</b>이라는 것이다.
     * "계근표 2건, 작업 전 사진 3건 있음" 은 공개해도 되는 값이고, 그것마저 막으면 대부분
     * 방문자에게 그 섹션이 빈칸이 된다.
     */
    SUMMARY
}
