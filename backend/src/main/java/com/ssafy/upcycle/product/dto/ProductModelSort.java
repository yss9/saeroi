package com.ssafy.upcycle.product.dto;

/**
 * 제품 목록 정렬 기준.
 *
 * <p>소비자 SHOP 1차 요구가 셋이다 — 최신순(기본)·가격 낮은순·가격 높은순. 인기순과
 * 판매순은 <b>집계할 데이터가 아직 없어</b> 넣지 않았다: 조회수도 판매량도 쌓는 곳이
 * 없으므로 지금 만들면 언제나 같은 순서인 정렬 옵션이 화면에 하나 더 생길 뿐이다.
 *
 * <p>모든 기준이 {@code id} 를 마지막 키로 쓴다. 정렬 값이 같은 제품들의 순서가 페이지마다
 * 달라지면 <b>같은 제품이 1페이지와 2페이지에 동시에 보이거나 어느 쪽에도 안 보인다</b> —
 * 가격은 같은 값이 흔해서 최신순보다 이 문제가 더 잘 드러난다.
 */
public enum ProductModelSort {

    /** 최근에 등록된 것부터. 기준을 주지 않으면 이것이다. */
    LATEST,

    /** 싼 것부터. */
    PRICE_ASC,

    /** 비싼 것부터. */
    PRICE_DESC
}
