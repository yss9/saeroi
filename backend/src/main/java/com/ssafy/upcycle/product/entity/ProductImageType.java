package com.ssafy.upcycle.product.entity;

/**
 * 상품 상세 갤러리에 걸리는 사진의 성격.
 *
 * <p>화면이 사진마다 다른 자리를 주기 때문에 종류를 남긴다 — 대표 사진은 첫 칸에 크게
 * 걸리고, 상세 컷은 확대해 보는 자리에 들어간다. 순서({@code sortOrder})만으로는 "세 번째
 * 사진" 이 무엇인지 알 수 없고, 브랜드가 순서를 바꾸면 그 의미가 통째로 흔들린다.
 *
 * <p>{@link #CONTEXT} 가 착용 사진으로 고정되지 않는 것이 중요하다. 지갑이나 리빙 제품에
 * 억지로 피팅 사진을 만들 수는 없으므로, 사용 장면이든 공간 연출이든 "제품이 쓰이는
 * 모습" 이면 여기 들어간다.
 */
public enum ProductImageType {

    /** 대표 사진. 갤러리에 있다면 한 장뿐이다. */
    MAIN,

    /** 다른 각도 — 측면·후면. */
    ANGLE,

    /** 소재·봉제선·부자재 확대. */
    DETAIL,

    /** 착용·사용·배치 장면. */
    CONTEXT
}
