package com.ssafy.upcycle.agent.service.step;

/**
 * 담당자가 그 단계에서 하는 행위의 종류.
 *
 * <p>카드 종류({@code PendingActionKind})와 일부러 나란히 두었다. 담당자가 화면에서 보는
 * 것이 결제창인지 지갑 창인지 단순 확인인지는 <b>마음의 준비가 다른 일</b>이라, 목록에서도
 * 구분해 보여야 한다.
 */
public enum StepAction {

    /** KakaoPay 결제. 돈이 나간다. */
    PAY,

    /** MetaMask 지갑 서명. 체인에 기록이 남는다. */
    SIGN,

    /** 단순 확인. 되돌리기 어려운 쓰기라 사람이 한 번 봐야 한다. */
    CONFIRM,

    /**
     * 상대 차례다. 담당자가 할 수 있는 일이 없다.
     *
     * <p><b>빼지 않고 담는다.</b> 목록에서 사라지면 모델이 "할 일이 없다" 로 읽고 재촉할
     * 도구를 찾는다. "기다리는 중" 이라고 적어 두어야 그대로 알린다.
     */
    WAIT
}
