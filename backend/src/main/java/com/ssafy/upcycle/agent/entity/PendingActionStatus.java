package com.ssafy.upcycle.agent.entity;

/** 제안된 액션이 어떻게 끝났는가. */
public enum PendingActionStatus {

    /** 사용자 응답을 기다리는 중. 대화당 여러 개가 동시에 떠 있을 수 있다. */
    PENDING,

    /** 사용자가 수행했고 결과를 받아 실제 도메인 서비스까지 호출했다. */
    COMPLETED,

    /** 사용자가 거절했다. 오류가 아니라 정상적인 선택이다. */
    REJECTED,

    /** 기한이 지났다. 오래된 제안이 나중에 되살아나는 것을 막는다. */
    EXPIRED,
    /**
     * 카드가 가리키는 일이 <b>다른 경로로 이미 처리됐다.</b>
     *
     * <p>담당자는 같은 거래를 거래 상세 화면에서도 다룰 수 있다. 화면에서 먼저 수령을
     * 확정하면 대화에 떠 있던 확인 카드는 할 일이 없어진다. 기한이 지난 것과 구분하는
     * 이유는 담당자에게 할 말이 다르기 때문이다 — 하나는 "다시 요청하세요", 다른 하나는
     * "이미 끝났습니다" 다.
     */
    STALE
}
