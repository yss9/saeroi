CREATE TABLE blockchain_operation (
    operation_id CHAR(66) NOT NULL,
    user_id BIGINT NOT NULL,
    chain_id BIGINT NOT NULL,
    contract_name VARCHAR(40) NOT NULL,
    contract_address VARCHAR(42) NOT NULL,
    function_name VARCHAR(100) NOT NULL,
    expected_selector VARCHAR(10) NOT NULL,
    reference_type ENUM('MATERIAL', 'TRADE', 'PROCESSING', 'PRODUCTION') NOT NULL,
    reference_id BIGINT NOT NULL,
    actor_wallet VARCHAR(42) NOT NULL,
    tx_hash CHAR(66) NULL,
    status VARCHAR(30) NOT NULL,
    attempt_count INT NOT NULL DEFAULT 0,
    next_attempt_at DATETIME NULL,
    block_number BIGINT NULL,
    log_index INT NULL,
    error_message TEXT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at DATETIME NULL,
    projected_at DATETIME NULL,
    CONSTRAINT pk_blockchain_operation PRIMARY KEY (operation_id),
    CONSTRAINT uk_blockchain_operation_tx UNIQUE (tx_hash),
    CONSTRAINT fk_blockchain_operation_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT chk_blockchain_operation_chain CHECK (chain_id > 0),
    CONSTRAINT chk_blockchain_operation_reference CHECK (reference_id > 0),
    INDEX idx_blockchain_operation_status_retry (status, next_attempt_at),
    INDEX idx_blockchain_operation_reference (reference_type, reference_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
